import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { getPages, getSelectedModules, MODULE_PAGES, SHARED_PAGES, validateAnswerShape, validatePage, validateSubmission } from "../lib/onboarding/questionnaire";
import type { Answers } from "../lib/onboarding/types";

const answer = (value: string | string[] | number | boolean | Record<string, string>) => ({ state: "answered" as const, value });
const source = readFileSync(new URL("../../onboarding.md", import.meta.url), "utf8");
const allPages = [...SHARED_PAGES, ...MODULE_PAGES];
const sourceQuestions = [...source.matchAll(/^\| ((?:P|M)\d{2}\.\d) \| (.+?) \|/gm)].map((match) => ({ id: match[1], label: match[2] }));
const implementedQuestions = allPages.flatMap((page) => page.questions.map((question) => ({ id: question.id, label: question.label })));
assert.equal(SHARED_PAGES.length, 16);
assert.equal(MODULE_PAGES.length, 26);
assert.equal(implementedQuestions.length, 127);
assert.deepEqual(implementedQuestions.sort((a, b) => a.id.localeCompare(b.id)), sourceQuestions.sort((a, b) => a.id.localeCompare(b.id)), "Every source question must preserve its stable ID and exact wording");
assert.equal(new Set(allPages.map((page) => page.id)).size, 42);

const mixed: Answers = { "P04.1": answer(["Physical goods", "Appointments"]), "P08.1": answer(["Website/store/application", "Chatbot", "Inventory", "ERP/CRM or other connections"]), "P08.2": answer(["Buy", "Book"]), "P11.1": answer(["None known"]), "P11.2": answer(["Ordinary contact/order details"]) };
assert.deepEqual(getSelectedModules(mixed), ["M01", "M02", "M03", "M04", "M07", "M13", "M18", "M19", "M20", "M21", "M26"]);
const pages = getPages(mixed);
assert.deepEqual(pages.slice(0, 12).map((page) => page.id), SHARED_PAGES.slice(0, 12).map((page) => page.id));
assert.deepEqual(pages.slice(-4).map((page) => page.id), ["P13", "P14", "P15", "P16"]);
assert.equal(new Set(pages.map((page) => page.id)).size, pages.length, "Routes must show each page only once");
assert.deepEqual(getSelectedModules({}, ["M06", "M06", "M99"]), ["M03", "M05", "M06"], "Print-on-demand adds catalog and delivery without adding stock");
assert.deepEqual(getSelectedModules({ "P11.2": answer(["Different user roles"]) }), ["M25", "M26"]);
assert.deepEqual(getSelectedModules({ "P11.1": { state: "unknown", value: "" } }), ["M25", "M26"]);
assert.deepEqual(getSelectedModules({ "M02.3": answer(["Content"]) }), [], "Inactive saved answers must not reactivate a route");
assert.deepEqual(getSelectedModules({ "P08.1": answer(["Website/store/application"]), "M02.3": answer(["Content"]) }), ["M01", "M02", "M22"]);

const complete: Answers = {};
for (const page of SHARED_PAGES) for (const question of page.questions) if (question.required) complete[question.id] = { state: "help", value: "" };
complete["P01.1"] = answer("Asha Verma");
complete["P01.3"] = answer("asha@example.test");
complete["P02.2"] = answer({ country: "India", timezone: "Asia/Kolkata" });
complete["P14.2"] = answer({ legalName: "Asha Verma", billingEmail: "asha@example.test" });
complete["P15.1"] = answer("asha@example.test");
complete["P13.1"] = answer("Use my project contact");
complete["P11.1"] = answer(["None known"]);
complete["P11.2"] = answer(["None"]);
complete["P11.3"] = answer(["None known"]);
complete["P16.2"] = answer(true);
complete["P16.3"] = answer(true);
assert.deepEqual(validateSubmission(complete), {}, "Guidance/follow-up responses must allow a usable submission");
assert.deepEqual(validateSubmission({ ...complete, "M03.1": answer("") }), {}, "Hidden required module fields cannot block submission");
assert.ok(validateSubmission(complete, [], { privacyReady: false })["P16.3"]);
assert.ok(validateSubmission({ ...complete, "P16.2": answer(false) })["P16.2"]);
assert.ok(validateSubmission({ ...complete, "P01.3": answer("invalid-email") })["P01.3"]);
assert.ok(validateSubmission({ ...complete, "P02.3": answer(["Phone"]) })["P01.4"]);
assert.equal(validateSubmission({ ...complete, "P02.3": answer(["Messaging/group"]) })["P01.4"], undefined, "A group channel is not necessarily phone-based");
assert.ok(validateSubmission({ ...complete, "P02.3": { ...answer(["Messaging/group"]), detail: "WhatsApp" } })["P01.4"]);
assert.ok(validateSubmission({ ...complete, "P14.2": answer({ legalName: "Asha", billingEmail: "" }) })["P14.2"]);
assert.ok(validateSubmission({ ...complete, "P15.2": answer({ name: "Colleague", email: "bad", name2: "Other", email2: "other@example.test" }) })["P15.2"]);
assert.ok(validateSubmission({ ...complete, "P12.1": answer("2026-02-30") })["P12.1"]);
assert.ok(validateSubmission({ ...complete, "P12.2": answer({ setup: "1000", currency: "" }) })["P12.2"]);
const goals = SHARED_PAGES.find((page) => page.id === "P06")!;
assert.ok(validatePage(goals, { "P06.1": answer("Launch a new project"), "P06.2": answer(["Sales", "Reporting"]), "P06.3": answer("Agree an improvement target") })["P06.2"]);
assert.equal(validatePage(goals, { "P06.1": answer("Launch a new project"), "P06.2": { ...answer(["Sales", "Reporting"]), priority: "Sales" }, "P06.3": answer("Agree an improvement target") })["P06.2"], undefined);
assert.ok(validatePage(SHARED_PAGES.find((page) => page.id === "P11")!, { "P11.1": answer(["None known", "Age restrictions"]), "P11.2": answer(["None"]), "P11.3": answer(["None known"]) })["P11.1"]);
// Public mutation arguments accept a value union; per-question validation must still
// reject values whose shape could otherwise impersonate a completed response.
const validateValue = (id: string, value: Parameters<typeof answer>[0]) => {
  const question = allPages.flatMap(page => page.questions).find(question => question.id === id)!;
  return validatePage({ id: id.split(".")[0], title: "Validation check", questions: [question] }, { [id]: answer(value) })[id];
};
assert.ok(validateValue("P01.1", true));
assert.ok(validateValue("P01.1", 123));
assert.ok(validateValue("P01.3", ["asha@example.test"]));
assert.ok(validateValue("P02.1", ["Owner/founder"]), "Single-choice fields require a scalar answer");
assert.ok(validateValue("P08.1", "Website/store/application"), "Checkbox groups require an array answer");
assert.ok(validateValue("P08.1", ["Inventory", "inventory"]), "Duplicated selections cannot satisfy a checkbox group");
assert.ok(validateValue("P10.1", true));
assert.ok(validateValue("P10.1", { Logo: "invented-status" }));
assert.ok(validateValue("P10.1", { Unknown: "ready" }));
assert.ok(validateValue("P10.1", { "Nothing yet": "not-available", Logo: "ready" }));
assert.equal(validateValue("P10.1", { Logo: "ready", "Brand guide": "needs-help" }), undefined);
assert.equal(validateValue("P10.1", { "Nothing yet": "not-available" }), undefined);
assert.ok(validateValue("M18.2", true), "Knowledge sources cannot be represented by a boolean");
assert.ok(validateValue("M15.3", true));
assert.ok(validateValue("M15.3", { currency: "", advertising: "1000" }));
assert.equal(validateValue("M15.3", { currency: "INR", advertising: "1000–2000" }), undefined);
assert.ok(validateValue("M20.3", { trigger: "Order received", result: "" }));
assert.equal(validateValue("M20.3", { trigger: "Quote accepted", result: "Create invoice" }), undefined);
assert.ok(validateValue("P04.2", "One\nTwo\nThree\nFour"), "Plain-text lists obey the same example limit as repeated entries");
assert.ok(validateValue("P04.2", ["Help me define this", "One", "Two", "Three"]), "A preset is valid only as a standalone string");
assert.equal(validateValue("P04.2", "Help me define this"), undefined);
assert.ok(validateValue("P14.2", { legalName: "Asha", billingEmail: "asha@example.test", isVerified: "true" }));
assert.ok(validateSubmission({ ...complete, "P14.2": { state: "help", value: "" } })["P14.2"]);
assert.equal(validateValue("P15.2", { name: "Colleague", email: "colleague@example.test", role: "Reviewer", access: "Review", name2: "Other", email2: "other@example.test" }), undefined);
assert.ok(validateValue("P15.2", { name: "Colleague", email: "colleague@example.test", administrator: "true" }));
assert.ok(validateValue("P16.2", "true"));
const catalogQuestion = MODULE_PAGES.find(page => page.id === "M03")!.questions[2];
assert.ok(validateAnswerShape(catalogQuestion, answer(["x".repeat(6001)])), "Nested list values obey the same data-size limit");
assert.equal(validateAnswerShape(catalogQuestion, answer("")), undefined, "An unfinished empty control remains saveable as a draft");
console.log("Onboarding checks passed: 42 pages, 127 exact questions, routing, inactive answers, validation, contact and privacy safeguards.");

const bookingAnswers = { "P08.2": answer(["Book"]), "M07.3": answer("Collect a deposit before confirming") };
assert.ok(getSelectedModules(bookingAnswers).includes("M13"), "Active bookings collecting money show payments questions");
assert.ok(!getSelectedModules({ "M07.3": answer("Collect a deposit") }).includes("M13"), "Inactive booking answers do not restore payment pages");
